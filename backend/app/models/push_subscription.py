"""Web Push Subscription Model Definition.

Stores browser Push API client subscriptions for dispatching PWA push alerts
(e.g., notifying superusers of pending requests or users of issued PINs).
"""

import uuid
from datetime import datetime
from sqlalchemy import String, Text, DateTime
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column
from backend.app.db.base import Base, utc_now


class PushSubscription(Base):
    """Web Push Subscription entity storing browser client encryption keys.

    Attributes:
        id: Primary key UUID identifying the subscription.
        user_email: Institutional email address of subscriber (indexed).
        endpoint: Unique browser push gateway delivery endpoint URL.
        p256dh: User agent public cryptographic key.
        auth: Authentication secret generated by user agent.
        created_at: Timezone-aware timestamp of subscription registration.
    """
    __tablename__ = "push_subscriptions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        doc="Primary key UUID for push subscription"
    )

    user_email: Mapped[str] = mapped_column(
        String(255),
        index=True,
        nullable=False,
        doc="Subscriber email address"
    )

    endpoint: Mapped[str] = mapped_column(
        Text,
        unique=True,
        nullable=False,
        doc="Browser push delivery endpoint URL"
    )

    p256dh: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Client P-256 Elliptic Curve public key"
    )

    auth: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Client authentication secret token"
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utc_now,
        nullable=False,
        doc="Timestamp of subscription establishment"
    )

    def __repr__(self) -> str:
        return f"<PushSubscription(user='{self.user_email}', endpoint='{self.endpoint[:30]}...')>"
